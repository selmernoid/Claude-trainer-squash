export const AREA_BY_ID = Object.fromEntries(AREAS.map((a) => [a.id, a])) as Record<AreaId, Area>;

export function findTopic(areaId: string, topicId: string): { area: Area; topic: Topic } | undefined {
  const area = AREAS.find((a) => a.id === areaId);
  const topic = area?.topics.find((t) => t.id === topicId);
  return area && topic ? { area, topic } : undefined;
}

export const ALL_TOPICS = AREAS.flatMap((area) => area.topics.map((topic) => ({ area, topic })));
